# utils package
# This package groups together all helper modules used by the
# AI Digital Twin Streamlit application:
#   - preprocessing.py : OpenCV image preprocessing for OCR
#   - ocr.py            : pytesseract-based text extraction
#   - regex_extractor.py: regex parsing of OCR text into structured fields
#   - prediction.py     : loads ML models and generates predictions
#   - digital_twin.py   : builds the virtual patient "digital twin" profile
